'use strict';

/**
 * Recreates specific products that were accidentally deleted from Shopify
 * (via Admin's Products page, not Zakeke) after already being imported.
 * Re-parses the same local EPDD file the original import used and filters
 * to just the given style codes, rather than re-running the full pilot
 * import — PILOT_STYLES/pilot_selection.json cover ~120 candidate styles,
 * far more than were actually imported, so an unfiltered re-run would
 * create dozens of unwanted products.
 *
 * Reuses bulkImportProducts as-is, so newly-created products get correct
 * pricing and automatic variant->image linking (src/shopify.js) same as
 * any other import.
 *
 * Usage:
 *   node scripts/recreate-missing-products.js --dry-run B100 B300 SP10
 *   node scripts/recreate-missing-products.js B100 B300 SP10
 */

const fs = require('fs');
const path = require('path');
const { parse } = require('csv-parse/sync');
require('dotenv').config({ path: path.join(__dirname, '../.env') });

const { buildShopifyProducts } = require('../src/mapper');
const { bulkImportProducts } = require('../src/shopify');

const EPDD_PATH = path.join(__dirname, '../data/raw/SanMar_EPDD.csv');
const PILOT_CSV_PATH = path.join(__dirname, '../data/processed/shopify_products_pilot.csv');

function styleCodeFromTitle(title) {
  const tokens = title.trim().split(/\s+/);
  return tokens[tokens.length - 1];
}

/**
 * Falls back to data/processed/shopify_products_pilot.csv (already
 * generated by build-shopify-csv.js) for styles whose EPDD row is past
 * wherever the raw file is truncated. Reconstructs the same nested shape
 * buildShopifyProducts produces, so it's a drop-in for bulkImportProducts.
 */
function loadProductsFromPilotCsv(styles) {
  const rows = parse(fs.readFileSync(PILOT_CSV_PATH, 'utf8'), { columns: true, trim: true });

  const byHandle = new Map();
  let currentHandle = null;
  for (const row of rows) {
    if (row.Handle) currentHandle = row.Handle;
    if (!byHandle.has(currentHandle)) {
      byHandle.set(currentHandle, {
        title: row.Title || null,
        body_html: row['Body (HTML)'] || '',
        vendor: row.Vendor || '',
        product_type: row.Type || '',
        tags: row.Tags || '',
        status: 'draft',
        variants: [],
        images: [],
        _seenImageSrcs: new Set(),
      });
    }
    const product = byHandle.get(currentHandle);
    if (row.Title) product.title = row.Title; // only the first row of a product carries it

    if (row['Image Src'] && !product._seenImageSrcs.has(row['Image Src'])) {
      product._seenImageSrcs.add(row['Image Src']);
      product.images.push({ src: row['Image Src'] });
    }

    if (row['Option1 Value']) {
      product.variants.push({
        option1: row['Option1 Value'],
        option2: row['Option2 Value'] || undefined,
        sku: row['Variant SKU'],
        price: row['Variant Price'],
        weight: row['Variant Grams'] ? Number(row['Variant Grams']) / 453.592 : undefined, // g -> lb, matches mapper.js units
        weight_unit: 'lb',
        inventory_management: 'shopify',
        inventory_policy: row['Variant Inventory Policy'] || 'deny',
        requires_shipping: row['Variant Requires Shipping'] !== 'false',
        taxable: row['Variant Taxable'] !== 'false',
        barcode: row['Variant Barcode'] || undefined,
        image: row['Variant Image'] ? { src: row['Variant Image'] } : undefined,
      });
    }
  }

  const products = [];
  for (const [handle, product] of byHandle) {
    delete product._seenImageSrcs;
    const style = product.title ? styleCodeFromTitle(product.title) : null;
    if (style && styles.includes(style)) {
      product.options = [
        { name: 'Color', values: [...new Set(product.variants.map((v) => v.option1))] },
        { name: 'Size', values: [...new Set(product.variants.map((v) => v.option2).filter(Boolean))] },
      ];
      product.style = style;
      products.push(product);
    }
  }
  return products;
}

async function main() {
  const args = process.argv.slice(2);
  const dryRun = args.includes('--dry-run');
  const styles = args.filter((a) => !a.startsWith('--'));

  if (styles.length === 0) {
    console.error('Usage: node scripts/recreate-missing-products.js [--dry-run] <STYLE1> <STYLE2> ...');
    process.exit(1);
  }

  console.log(`Parsing SanMar_EPDD.csv, filtering to styles: ${styles.join(', ')}...`);
  const allProducts = await buildShopifyProducts(EPDD_PATH);
  const products = allProducts.filter((p) => styles.includes(p.style));

  console.log(`Matched ${products.length}/${styles.length} requested styles:`);
  for (const p of products) console.log(`  ${p.style} — ${p.title} (${p.variants.length} variants)`);

  let missing = styles.filter((s) => !products.some((p) => p.style === s));
  if (missing.length) {
    console.log(`  NOT FOUND in EPDD (truncated file): ${missing.join(', ')} — falling back to shopify_products_pilot.csv`);
    const fromCsv = loadProductsFromPilotCsv(missing);
    for (const p of fromCsv) console.log(`  ${p.style} — ${p.title} (${p.variants.length} variants) [from pilot CSV]`);
    products.push(...fromCsv);
    missing = styles.filter((s) => !products.some((p) => p.style === s));
    if (missing.length) console.log(`  STILL NOT FOUND anywhere: ${missing.join(', ')}`);
  }

  if (products.length === 0) {
    console.log('Nothing to import.');
    return;
  }

  await bulkImportProducts(products, { dryRun });
}

main().catch((err) => {
  console.error('Recreate error:', err.message);
  process.exit(1);
});
